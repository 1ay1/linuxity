#!/usr/bin/env python3
"""Generate conform/sysno_names.inc from the Sysno enum.

The enum in abi/sysno.hpp is the single source of truth for syscall
identities. Rather than hand-maintain a parallel name table that silently
drifts, we derive it. Run this when Sysno gains a member; the output is
checked in, so the build never depends on python.

    tools/gen_sysno_names.py > include/linuxity/conform/sysno_names.inc
"""
import pathlib
import re
import sys

HEADER = pathlib.Path("include/linuxity/abi/sysno.hpp")


def enum_members(text: str) -> list[str]:
    """Pull the identifiers out of `enum class Sysno { ... };`."""
    m = re.search(r"enum class Sysno\s*\{(.*?)\n\};", text, re.S)
    if not m:
        sys.exit("gen_sysno_names: could not find `enum class Sysno` body")

    body = m.group(1)
    body = re.sub(r"//[^\n]*", "", body)          # drop line comments
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)  # and block comments

    names = []
    for tok in body.split(","):
        tok = tok.strip()
        if not tok:
            continue
        # `unknown = 0` -> `unknown`
        tok = tok.split("=")[0].strip()
        if re.fullmatch(r"[A-Za-z_]\w*", tok):
            names.append(tok)
    return names


def main() -> None:
    if not HEADER.exists():
        sys.exit(f"gen_sysno_names: {HEADER} not found (run from the repo root)")

    names = enum_members(HEADER.read_text())
    if len(names) < 100:
        sys.exit(f"gen_sysno_names: only parsed {len(names)} members, "
                 "the enum shape must have changed")

    out = sys.stdout
    out.write("// GENERATED by tools/gen_sysno_names.py -- do not edit.\n")
    out.write("// Source of truth: include/linuxity/abi/sysno.hpp\n")
    out.write(f"// {len(names)} members.\n")
    out.write("//\n")
    out.write("// A name per Sysno, for divergence reports. Kept as an .inc so\n")
    out.write("// the table cannot drift from the enum without this file\n")
    out.write("// changing in the same commit.\n")
    for n in names:
        out.write(f"LX_SYSNO_NAME({n})\n")


if __name__ == "__main__":
    main()
