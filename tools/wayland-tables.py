#!/usr/bin/env python3
"""Generate linuxity-display's Wayland protocol tables from protocol XML.

    tools/wayland-tables.py third_party/wayland-protocols/*.xml

writes src/display/protocol/protocol.hpp and protocol.cpp. The output is
committed (the build never needs Python); rerun this after adding a protocol.

Per interface it emits a struct named after it in CamelCase:

    struct WlSurface {
        static const wire::Interface iface;
        struct Req { enum : std::uint16_t { destroy, attach, ... }; };
        struct Ev  { enum : std::uint16_t { enter, leave, ... }; };
        enum class Error : std::uint32_t { invalid_scale = 0, ... };
    };

and wire tables in libwayland's signature alphabet (i u f s o n a h, '?' for
nullable). An untyped new_id (wl_registry.bind) expands to "sun" exactly as
it travels on the wire: interface name, version, id.
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

KEYWORDS = {"delete", "default", "export", "new", "class", "union", "and", "or",
            "not", "xor", "inline", "register", "operator", "this", "switch",
            "case", "struct", "enum", "auto", "bool", "char", "int",
            "float", "double", "void", "return", "break", "continue"}
CODES = {"int": "i", "uint": "u", "fixed": "f", "string": "s", "object": "o",
         "new_id": "n", "array": "a", "fd": "h"}


def camel(name):
    return "".join(p[:1].upper() + p[1:] for p in name.split("_"))


def ident(name):
    if name[0].isdigit():
        name = "_" + name
    return name + "_" if name in KEYWORDS else name


def messages(iface, tag):
    out = []
    for m in iface.findall(tag):
        sig, types = "", []
        for a in m.findall("arg"):
            t = a.get("type")
            if t == "new_id" and not a.get("interface"):
                sig += "sun"
                types += [None, None, None]
                continue
            if a.get("allow-null") == "true":
                sig += "?"
            sig += CODES[t]
            types.append(a.get("interface") if t in ("object", "new_id") else None)
        out.append({
            "name": m.get("name"),
            "sig": sig,
            "types": types,
            "since": int(m.get("since", "1")),
            "destructor": m.get("type") == "destructor",
        })
    return out


def main(paths):
    ifaces = []
    for p in paths:
        root = ET.parse(p).getroot()
        for i in root.findall("interface"):
            ifaces.append({
                "name": i.get("name"),
                "version": int(i.get("version")),
                "requests": messages(i, "request"),
                "events": messages(i, "event"),
                "enums": [(e.get("name"), e.get("bitfield") == "true",
                           [(x.get("name"), x.get("value")) for x in e.findall("entry")])
                          for e in i.findall("enum")],
                "file": os.path.basename(p),
            })
    known = {i["name"] for i in ifaces}

    here = os.path.dirname(os.path.abspath(__file__))
    outdir = os.path.join(here, "..", "src", "display", "protocol")
    os.makedirs(outdir, exist_ok=True)
    banner = ("// GENERATED by tools/wayland-tables.py from third_party/wayland-protocols/.\n"
              "// Do not edit; rerun the generator.\n")

    h = [banner, "#pragma once\n", '#include "../wire/wire.hpp"\n',
         "#include <cstdint>\n", "namespace lx::display::proto {\n"]
    for i in ifaces:
        h.append(f"\n// {i['name']} v{i['version']} ({i['file']})")
        h.append(f"struct {camel(i['name'])} {{")
        h.append("    static const wire::Interface iface;")
        h.append(f"    static constexpr std::uint32_t version = {i['version']};")
        for tag, key in (("Req", "requests"), ("Ev", "events")):
            if i[key]:
                names = ", ".join(ident(m["name"]) for m in i[key])
                h.append(f"    struct {tag} {{ enum : std::uint16_t {{ {names} }}; }};")
        for ename, bitfield, entries in i["enums"]:
            body = ", ".join(f"{ident(n)} = {v}" for n, v in entries)
            if bitfield:
                h.append(f"    struct {camel(ename)} {{ enum : std::uint32_t {{ {body} }}; }};")
            else:
                h.append(f"    enum class {camel(ename)} : std::uint32_t {{ {body} }};")
        h.append("};")
    h.append("\n}  // namespace lx::display::proto\n")

    c = [banner, '#include "protocol.hpp"\n', "namespace lx::display::proto {\n",
         "namespace {", "using wire::Interface;", "using wire::Message;"]
    for i in ifaces:
        cn = camel(i["name"])
        for key in ("requests", "events"):
            for k, m in enumerate(i[key]):
                if any(m["types"]):
                    refs = ", ".join(f"&{camel(t)}::iface" if t in known else "nullptr"
                                     for t in m["types"])
                    c.append(f"const Interface* const {cn}_{key}_{k}_types[] = {{ {refs} }};")
        for key in ("requests", "events"):
            if not i[key]:
                continue
            rows = []
            for k, m in enumerate(i[key]):
                types = f"{cn}_{key}_{k}_types" if any(m["types"]) else "{}"
                flags = "true" if m["destructor"] else "false"
                rows.append(f'    {{"{m["name"]}", "{m["sig"]}", {m["since"]}, {flags}, {types}}},')
            c.append(f"const Message {cn}_{key}[] = {{")
            c += rows
            c.append("};")
    c.append("}  // namespace\n")
    for i in ifaces:
        cn = camel(i["name"])
        req = f"{cn}_requests" if i["requests"] else "{}"
        ev = f"{cn}_events" if i["events"] else "{}"
        c.append(f'const Interface {cn}::iface{{"{i["name"]}", {i["version"]}, {req}, {ev}}};')
    c.append("\n}  // namespace lx::display::proto\n")

    with open(os.path.join(outdir, "protocol.hpp"), "w") as f:
        f.write("\n".join(h))
    with open(os.path.join(outdir, "protocol.cpp"), "w") as f:
        f.write("\n".join(c))
    print(f"{len(ifaces)} interfaces -> {os.path.relpath(outdir)}")


if __name__ == "__main__":
    main(sys.argv[1:] or sorted(
        os.path.join(os.path.dirname(__file__), "..", "third_party", "wayland-protocols", f)
        for f in os.listdir(os.path.join(os.path.dirname(__file__), "..", "third_party", "wayland-protocols"))
        if f.endswith(".xml")))
