#!/usr/bin/env python3
"""Assemble tools/fastcall/handler.S into an embeddable C++ header.

    tools/fastcall/build.py   ->  include/linuxity/runtime/hvf_fastcall_blob.hpp

The handler is position-independent except for one movz/movk pair that
carries the dispatch table's guest-physical address; we record its word
index so the runtime can patch it at install time. Needs clang + ld.lld
(the same toolchain tools/vdso/build.py uses). The generated header is
checked in, so building linuxity never needs a cross toolchain.
"""
import pathlib, re, shutil, subprocess, sys, tempfile

here = pathlib.Path(__file__).resolve().parent
root = here.parent.parent
out = root / "include/linuxity/runtime/hvf_fastcall_blob.hpp"

def tool(*names):
    for n in names:
        p = shutil.which(n) or (pathlib.Path("/opt/homebrew/opt/llvm/bin") / n)
        if p and pathlib.Path(p).exists():
            return str(p)
    sys.exit(f"missing tool: {names}")

clang, objcopy, nm = tool("clang"), tool("llvm-objcopy"), tool("llvm-nm")
with tempfile.TemporaryDirectory() as t:
    o, binf = f"{t}/h.o", f"{t}/h.bin"
    subprocess.check_call([clang, "--target=aarch64-linux-gnu", "-c",
                           str(here / "handler.S"), "-o", o])
    subprocess.check_call([objcopy, "-O", "binary", "--only-section=.text", o, binf])
    blob = pathlib.Path(binf).read_bytes()
    syms = subprocess.check_output([nm, o], text=True)

def sym(name):
    m = re.search(r"^([0-9a-f]+)\s+\S+\s+" + re.escape(name) + r"$", syms, re.M)
    if not m: sys.exit(f"symbol {name} not found in:\n{syms}")
    return int(m.group(1), 16)

begin, imm = sym("_fast_table_imm"), None
imm_word = (sym("_fast_table_imm") - sym("_fast_begin")) // 4
assert len(blob) % 4 == 0, len(blob)
words = [int.from_bytes(blob[i:i+4], "little") for i in range(0, len(blob), 4)]

# Sanity: the patch site must be movz x16,#0 then movk x16,#0,lsl #16.
movz, movk = words[imm_word], words[imm_word + 1]
assert movz == 0xd2800010, f"patch site 0 is {movz:#x}, not movz x16,#0"
assert movk == 0xf2a00010, f"patch site 1 is {movk:#x}, not movk x16,#0,lsl#16"

rows = [", ".join(f"0x{w:08x}" for w in words[i:i+6]) for i in range(0, len(words), 6)]
out.write_text(
    "// GENERATED by tools/fastcall/build.py from tools/fastcall/handler.S\n"
    "// -- do not edit. Rebuild after changing the handler.\n"
    "#pragma once\n#include <cstddef>\n#include <cstdint>\n\n"
    "namespace lx::runtime::fastcall {\n"
    "// The EL1 fast-path handler, as instruction words.\n"
    f"inline constexpr std::size_t kCodeWords = {len(words)};\n"
    "// Index of the `movz x16,#lo` whose next word is `movk x16,#hi,lsl#16`:\n"
    "// the runtime patches both with the dispatch table's address.\n"
    f"inline constexpr std::size_t kTableImmWord = {imm_word};\n"
    "inline constexpr std::uint32_t kCode[kCodeWords] = {\n    "
    + ",\n    ".join(rows) + "\n};\n}  // namespace lx::runtime::fastcall\n")
print(f"{out.relative_to(root)}: {len(words)} instructions, "
      f"table imm at word {imm_word}")
