#!/usr/bin/env python3
"""Regenerate linuxity's syscall tables from a kernel's own headers.

The syscall tables are the one place in linuxity where a typo is both easy
and catastrophic: a wrong number silently routes one syscall to another's
handler, so the guest gets a plausible answer to a question it never asked.
Hand-maintaining 700 entries across two ABIs is not a reasonable thing to
ask of a person, so they are GENERATED and the result is checked in.

Usage:
    tools/gen_sysno.py /path/to/aarch64/rootfs [--check]

The rootfs must contain the kernel UAPI headers (any Linux distro rootfs
does: /usr/include/asm/unistd_64.h). --check verifies the checked-in tables
match the headers instead of rewriting them, which is what CI should run so
a new kernel release shows up as a failing test rather than a silent gap.

Outputs:
    include/linuxity/abi/sysno.hpp   the enum + both decode tables
    tests/sysno_aarch64.inc          {nr, name} pairs the conformance test
                                     asserts against
"""
from __future__ import annotations

import pathlib
import re
import sys

# x86-64 is not derivable from a rootfs header on an aarch64 machine, so its
# numbering lives here, transcribed from arch/x86/entry/syscalls/syscall_64.tbl.
# It is append-only in the kernel, which is why a static table is safe.
X86_64_TBL = pathlib.Path(__file__).with_name("syscall_64.tbl")


def parse_unistd(root: pathlib.Path) -> dict[int, str]:
    """Pull __NR_<name> <number> out of the kernel's aarch64 header."""
    header = root / "usr/include/asm/unistd_64.h"
    if not header.exists():
        sys.exit(f"{header} not found -- point this at an aarch64 Linux rootfs")
    out: dict[int, str] = {}
    for m in re.finditer(r"#define\s+__NR_(\w+)\s+(\d+)", header.read_text()):
        out[int(m.group(2))] = m.group(1)
    return out


def parse_x86() -> dict[int, str]:
    out: dict[int, str] = {}
    for line in X86_64_TBL.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) >= 3 and parts[0].isdigit() and parts[1] in ("common", "64"):
            out[int(parts[0])] = parts[2]
    return out


def wrap(names: list[str], per: int = 6, indent: str = "    ") -> str:
    return "\n".join(
        indent + ", ".join(names[i : i + per]) + ","
        for i in range(0, len(names), per)
    )


def render(arm: dict[int, str], x86: dict[int, str], existing_order: list[str]) -> str:
    allnames = sorted(set(arm.values()) | set(x86.values()))
    keep = [n for n in existing_order if n in allnames or n == "unknown"]
    order = keep + [n for n in allnames if n not in keep]
    body = [n for n in order if n != "unknown"]

    def table(arch: str, m: dict[int, str], note: str) -> str:
        rows = [f"        case Arch::{arch}:", "            switch (nr) {",
                f"                // {note}"]
        rows += [f"                case {nr}: return Sysno::{m[nr]};" for nr in sorted(m)]
        rows += ["                default: return Sysno::unknown;", "            }"]
        return "\n".join(rows)

    return f"""// linuxity/abi/sysno.hpp
//
// The syscall identity: one canonical name per operation, and the per-ABI
// number tables that map onto it.
//
// GENERATED by tools/gen_sysno.py from the kernel's own headers. Do not edit
// by hand: a mistyped number routes one syscall to another's handler, which
// is the one class of bug here that produces plausible wrong answers instead
// of errors. tests/test_conformance.cpp asserts every number in the ABI
// decodes, so a new kernel release fails the build rather than going unnoticed.
#pragma once

#include <cstdint>

namespace lx::abi {{

// The host/guest instruction set (they are equal in the native-speed model).
enum class Arch {{ x86_64, aarch64 }};

// Every syscall in both 64-bit Linux ABIs we target, plus `unknown` for a
// number the kernel has not assigned.
enum class Sysno {{
    unknown = 0,
{wrap(body)}
}};

// Decode an arch-specific raw syscall number into the canonical identity.
// Both tables are COMPLETE: every number the kernel defines appears, so a
// guest can never see `unknown` for a syscall that actually exists.
[[nodiscard]] constexpr Sysno decode(Arch a, std::uint64_t nr) noexcept {{
    switch (a) {{
{table("x86_64", x86, "x86-64: arch/x86/entry/syscalls/syscall_64.tbl")}
{table("aarch64", arm, "aarch64: asm-generic, via asm/unistd_64.h")}
    }}
    return Sysno::unknown;
}}

}} // namespace lx::abi
"""


def main() -> int:
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    root = pathlib.Path(sys.argv[1])
    check = "--check" in sys.argv
    repo = pathlib.Path(__file__).resolve().parent.parent

    arm = parse_unistd(root)
    x86 = parse_x86() if X86_64_TBL.exists() else {}
    if not x86:
        # Preserve the existing x86 table rather than dropping it.
        src = (repo / "include/linuxity/abi/sysno.hpp").read_text()
        seg = src[src.index("case Arch::x86_64") : src.index("case Arch::aarch64")]
        x86 = {int(m.group(1)): m.group(2)
               for m in re.finditer(r"case (\d+): return Sysno::(\w+);", seg)}

    hdr = repo / "include/linuxity/abi/sysno.hpp"
    old = hdr.read_text()
    order = []
    enum_seg = old[old.index("enum class Sysno {") : old.index("};", old.index("enum class Sysno {"))]
    for tok in re.findall(r"\b([a-z_][a-z_0-9]*)\b", re.sub(r"//.*", "", enum_seg)):
        if tok not in ("enum", "class", "unknown") and tok not in order:
            order.append(tok)

    new = render(arm, x86, ["unknown"] + order)
    inc = "\n".join(
        ["// GENERATED by tools/gen_sysno.py from the kernel's aarch64 headers.",
         "// Each entry is { number, name }; test_conformance asserts every one decodes."]
        + [f'    {{{nr}, "{arm[nr]}"}},' for nr in sorted(arm)]
    ) + "\n"
    incp = repo / "tests/sysno_aarch64.inc"

    if check:
        bad = False
        if hdr.read_text() != new:
            print("STALE: include/linuxity/abi/sysno.hpp differs from the kernel headers")
            bad = True
        if incp.read_text() != inc:
            print("STALE: tests/sysno_aarch64.inc differs from the kernel headers")
            bad = True
        if not bad:
            print(f"up to date: {len(arm)} aarch64 + {len(x86)} x86-64 syscalls")
        return 1 if bad else 0

    hdr.write_text(new)
    incp.write_text(inc)
    print(f"wrote {len(arm)} aarch64 + {len(x86)} x86-64 syscalls")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
