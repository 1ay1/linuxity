#!/usr/bin/env python3
"""Build the linuxity aarch64 vDSO and embed it as a C++ header.

    tools/vdso/build.py            -> include/linuxity/runtime/hvf_vdso_blob.hpp

Needs clang (any target-capable build) and ld.lld. The generated header is
checked in, so building linuxity itself never needs a cross toolchain.
"""
import pathlib, shutil, subprocess, sys, tempfile

here = pathlib.Path(__file__).resolve().parent
root = here.parent.parent
out = root / "include/linuxity/runtime/hvf_vdso_blob.hpp"

def tool(*names):
    for n in names:
        p = shutil.which(n) or (pathlib.Path("/opt/homebrew/opt/llvm/bin") / n)
        if p and pathlib.Path(p).exists():
            return str(p)
    sys.exit(f"missing tool: {names}")

clang, lld = tool("clang"), tool("ld.lld")
with tempfile.TemporaryDirectory() as t:
    o, so = f"{t}/vdso.o", f"{t}/vdso.so"
    subprocess.check_call([clang, "--target=aarch64-linux-gnu", "-O2", "-fPIC",
        "-ffreestanding", "-fno-stack-protector", "-fno-asynchronous-unwind-tables",
        "-fno-jump-tables", "-c", str(here / "vdso.c"), "-o", o])
    subprocess.check_call([lld, "-shared", "--hash-style=both", "-soname=linux-vdso.so.1",
        f"--version-script={here / 'vdso.lds'}", "-T", str(here / "vdso.ld"),
        "-z", "max-page-size=4096", "-z", "noexecstack", "--build-id=none",
        "-z", "norelro", "--no-rosegment", "-o", so, o])
    blob = pathlib.Path(so).read_bytes()

rows = [", ".join(f"0x{b:02x}" for b in blob[i:i + 16]) for i in range(0, len(blob), 16)]
out.write_text(
    "// GENERATED by tools/vdso/build.py from tools/vdso/vdso.c -- do not edit.\n"
    "#pragma once\n#include <cstddef>\n#include <cstdint>\n\n"
    "namespace lx::runtime::vdso {\n"
    f"inline constexpr std::size_t kImageSize = {len(blob)};\n"
    "alignas(16) inline constexpr std::uint8_t kImage[kImageSize] = {\n    "
    + ",\n    ".join(rows) + "\n};\n}  // namespace lx::runtime::vdso\n")
print(f"{out.relative_to(root)}: {len(blob)} bytes")
