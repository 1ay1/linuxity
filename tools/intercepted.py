#!/usr/bin/env python3
"""Generate the list of syscalls linuxity INTERCEPTS.

A syscall linuxity merely FORWARDS needs no differential proof: the real
kernel runs it, so it is correct by construction. Only an intercepted
handler -- one that can answer differently from the kernel -- can diverge,
and only those belong in the conformance denominator.

That distinction used to be a hand-written constant, and it had drifted in
the flattering direction: it counted forwarded syscalls, so coverage read
84% when the honest figure was 70%. A number nobody maintains drifts toward
whatever looks good, so it is derived from the source now.

The rule is mechanical. For each `case Sysno::X` arm in the dispatcher:
  * only outcome is fwd()            -> forwarded, no proof needed
  * anything else (val/eno/Virtualize/Redirect/ArgRewrite/do_*/path_*),
    or fwd() guarded by a requires/if -> intercepted, must be proven

Usage:
    tools/intercepted.py --check          # fail if the .inc is stale
    tools/intercepted.py --write          # regenerate it
    tools/intercepted.py --list           # print both groups
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "include/linuxity/abi/syscall.hpp")
INC = os.path.join(ROOT, "include/linuxity/conform/intercepted.inc")

# Outcomes a handler can produce. Everything except a bare fwd() means the
# answer can differ from the kernel's.
OUTCOME = re.compile(
    r"\b(fwd|val|eno|sig|Virtualize|Redirect|ArgRewrite|SockRewrite|"
    r"ExecInterp|Inject|Exited)\s*[({]")
DELEGATE = re.compile(r"\breturn\s+(do_\w+|path_\w+|\w+_xattr)\s*\(")
# Several labels often share one line:
#     case Sysno::getpid:  case Sysno::gettid:  case Sysno::getppid:
# Matching only the first silently dropped the rest from the denominator,
# so scan for every label on the line and keep whatever follows the last.
CASE_ANY = re.compile(r"case Sysno::(\w+)\s*:")
CASE_LINE = re.compile(r"^\s*case Sysno::")


def classify(text):
    """-> (forwarded, intercepted), both sorted name lists."""
    arms, pending, body, in_arm = {}, [], [], False

    def flush():
        # Consecutive `case` labels with no body between them FALL THROUGH
        # and share the next one, so `pending` must survive an empty body --
        # clearing it there silently dropped every such label (getxattr,
        # setxattr, getegid... all vanished from the denominator).
        nonlocal pending, body
        if not body:
            return
        for n in pending:
            arms.setdefault(n, []).extend(body)
        pending, body = [], []

    for ln in text.splitlines():
        if CASE_LINE.match(ln):
            flush()
            names = CASE_ANY.findall(ln)
            pending.extend(names)
            in_arm = True
            # Anything after the LAST label on the line is already body.
            rest = ln[ln.rfind(":") + 1:].strip()
            if rest:
                body.append(rest)
            continue
        if in_arm:
            # The default arm or the end of the switch closes the group.
            if re.match(r"\s*(default:|\}\s*$)", ln):
                flush()
                in_arm = False
                continue
            body.append(ln.strip())
    flush()

    fwd_only, intercepted = [], []
    for name, b in sorted(arms.items()):
        blob = re.sub(r"//.*", "", " ".join(b))   # drop comments
        outcomes = set(OUTCOME.findall(blob))
        if outcomes == {"fwd"} and not DELEGATE.search(blob):
            fwd_only.append(name)
        else:
            intercepted.append(name)
    return fwd_only, intercepted


def render(intercepted):
    return (
        "// GENERATED by tools/intercepted.py -- do not edit.\n"
        "//\n"
        "// The syscalls linuxity INTERCEPTS: those whose answer can differ\n"
        "// from the kernel's, and which therefore need differential proof.\n"
        "// Syscalls that only forward are excluded -- the real kernel runs\n"
        "// them, so they are correct by construction and counting them would\n"
        "// inflate the coverage number.\n"
        "//\n"
        "// Regenerate with: tools/intercepted.py --write\n"
        + "".join(f"LX_INTERCEPTED({n})\n" for n in intercepted)
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args()

    fwd, icept = classify(open(SRC).read())

    if a.list:
        print(f"forwarded ({len(fwd)}):   " + " ".join(fwd))
        print()
        print(f"intercepted ({len(icept)}): " + " ".join(icept))
        return 0

    want = render(icept)
    have = open(INC).read() if os.path.exists(INC) else None

    if a.write:
        if have != want:
            os.makedirs(os.path.dirname(INC), exist_ok=True)
            open(INC, "w").write(want)
            print(f"intercepted.py: wrote {len(icept)} handlers")
        else:
            print(f"intercepted.py: up to date ({len(icept)} handlers)")
        return 0

    if a.check:
        if have != want:
            print("intercepted.py: intercepted.inc is STALE -- run "
                  "tools/intercepted.py --write", file=sys.stderr)
            return 1
        print(f"intercepted.py: up to date ({len(icept)} handlers)")
        return 0

    ap.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
